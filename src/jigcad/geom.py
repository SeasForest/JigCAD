"""Geometry helpers on top of build123d (the only module family that talks to the kernel)."""
from __future__ import annotations

import math
from typing import Iterable

from build123d import Axis, BoundBox, GeomType, Plane, Vector

EPS = 0.05  # tool overshoot above the entry face, avoids coplanar booleans

# outward normal and in-plane x direction for each named box face
FACE_FRAMES = {
    "top":    ((0, 0, 1), (1, 0, 0)),
    "bottom": ((0, 0, -1), (1, 0, 0)),
    "front":  ((0, -1, 0), (1, 0, 0)),
    "back":   ((0, 1, 0), (-1, 0, 0)),
    "right":  ((1, 0, 0), (0, 1, 0)),
    "left":   ((-1, 0, 0), (0, -1, 0)),
}


def bbox_anchors(bb: BoundBox) -> dict[str, Plane]:
    c = bb.center()
    out = {"center": Plane(origin=c, x_dir=(1, 0, 0), z_dir=(0, 0, 1))}
    for name, (n, x) in FACE_FRAMES.items():
        o = Vector(c)
        if n[0]:
            o.X = bb.max.X if n[0] > 0 else bb.min.X
        if n[1]:
            o.Y = bb.max.Y if n[1] > 0 else bb.min.Y
        if n[2]:
            o.Z = bb.max.Z if n[2] > 0 else bb.min.Z
        out[name] = Plane(origin=o, x_dir=x, z_dir=n)
    return out


def place(plane: Plane, at=None, rotate: float = 0.0, flip: bool = False) -> Plane:
    """Offset a plane by local (u, v[, w]) and rotate about its normal."""
    p = plane
    if flip:
        p = Plane(origin=p.origin, x_dir=p.x_dir, z_dir=-p.z_dir)
    if at:
        u, v = float(at[0]), float(at[1])
        w = float(at[2]) if len(at) > 2 else 0.0
        o = p.origin + p.x_dir * u + p.y_dir * v + p.z_dir * w
        p = Plane(origin=o, x_dir=p.x_dir, z_dir=p.z_dir)
    if rotate:
        a = math.radians(rotate)
        x = p.x_dir * math.cos(a) + p.y_dir * math.sin(a)
        p = Plane(origin=p.origin, x_dir=x, z_dir=p.z_dir)
    return p


def vec(v) -> tuple[float, float, float]:
    return (round(v.X, 4), round(v.Y, 4), round(v.Z, 4))


def bbox_dict(bb: BoundBox) -> dict:
    return {"min": vec(bb.min), "max": vec(bb.max), "size": vec(bb.size)}


def diag(bb: BoundBox) -> float:
    return math.sqrt(bb.size.X ** 2 + bb.size.Y ** 2 + bb.size.Z ** 2)


def _on_surface(pt: Vector, shape, tol=1e-3) -> bool:
    from build123d import Vertex
    return shape.distance_to(Vertex(pt.X, pt.Y, pt.Z)) < tol


def select_edges(body, selector: str, restrict=None, bb: BoundBox | None = None):
    """Semantic edge selection (never topological indices).

    selector: all | vertical | horizontal | top | bottom | outer_vertical |
              circular | linear
    restrict: optional shape; only edges lying on its original edges are kept
              (= edges generated by that feature, not later features on its faces).
    """
    edges = list(body.edges())
    bb = bb or body.bounding_box()
    tol = 1e-3
    if restrict is not None:
        # keep only edges lying on the ORIGINAL edges of that feature's geometry
        from build123d import Compound
        ref = Compound(list(restrict.edges()))
        edges = [e for e in edges if _on_surface(e.center(), ref) and
                 _on_surface(e.position_at(0.25), ref)]
        bb = restrict.bounding_box() if selector in ("top", "bottom") else bb

    def is_vertical(e):
        if e.geom_type != GeomType.LINE:
            return False
        d = (e.end_point() - e.start_point()).normalized()
        return abs(abs(d.Z) - 1) < 1e-6

    def is_horizontal(e):
        p0, p1, pm = e.start_point(), e.end_point(), e.center()
        return abs(p0.Z - p1.Z) < tol and abs(p0.Z - pm.Z) < tol

    bbody = body.bounding_box()
    if selector == "all":
        sel = edges
    elif selector == "vertical":
        sel = [e for e in edges if is_vertical(e)]
    elif selector == "outer_vertical":  # vertical edges on the XY bounding-box corners
        sel = [e for e in edges if is_vertical(e) and _on_bbox_corner(e, bbody)]
    elif selector == "horizontal":
        sel = [e for e in edges if is_horizontal(e)]
    elif selector == "top":
        z = bb.max.Z
        sel = [e for e in edges if is_horizontal(e) and abs(e.center().Z - z) < tol]
    elif selector == "bottom":
        z = bb.min.Z
        sel = [e for e in edges if is_horizontal(e) and abs(e.center().Z - z) < tol]
    elif selector == "circular":
        sel = [e for e in edges if e.geom_type == GeomType.CIRCLE]
    elif selector == "linear":
        sel = [e for e in edges if e.geom_type == GeomType.LINE]
    else:
        raise ValueError(f"unknown edge selector '{selector}' (all|vertical|outer_vertical|horizontal|top|bottom|circular|linear)")
    return sel


def _on_bbox_corner(e, bb: BoundBox, tol=1e-3) -> bool:
    c = e.center()
    return ((abs(c.X - bb.min.X) < tol or abs(c.X - bb.max.X) < tol) and
            (abs(c.Y - bb.min.Y) < tol or abs(c.Y - bb.max.Y) < tol))


def ray_hits(body, origin: Vector, direction: Vector) -> list[tuple[float, bool]]:
    """Intersections of a ray with the body: (distance, entering?) sorted."""
    from build123d import Axis
    d = direction.normalized()
    out = []
    for p, n in body.find_intersection_points(Axis(origin, d)):
        t = (p - origin).dot(d)
        if t > -1e-6:
            out.append((t, n.dot(d) < 0))
    out.sort()
    return out


def classify_points(solid, pts: Iterable[Vector]) -> list[bool]:
    """True = inside material."""
    from OCP.BRepClass3d import BRepClass3d_SolidClassifier
    from OCP.gp import gp_Pnt
    from OCP.TopAbs import TopAbs_IN
    cls = BRepClass3d_SolidClassifier(solid.wrapped)
    out = []
    for p in pts:
        cls.Perform(gp_Pnt(p.X, p.Y, p.Z), 1e-6)
        out.append(cls.State() == TopAbs_IN)
    return out


def face_normal_at(face, pt: Vector) -> Vector:
    try:
        u, v = face.param_at_point(pt) if hasattr(face, "param_at_point") else (0.5, 0.5)
        return face.normal_at(u, v)
    except Exception:  # noqa: BLE001
        return face.normal_at(pt)


def parallel(a: Vector, b: Vector, tol=1e-4) -> bool:
    return abs(abs(a.normalized().dot(b.normalized())) - 1) < tol


def axis_z() -> Axis:
    return Axis.Z
